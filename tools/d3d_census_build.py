#!/usr/bin/env python3
"""Writes a Direct3D census build's hooks (sa2-nx's census, docs/api-renderer.md; src/me/futari_d3d_census.h):

  out/census/census_default.cpp  every function of default.xex's Direct3D range, hooked (the executable)
  out/census/census_core.cpp     every function of each game core's Direct3D, hooked (#if FUTARI_CORE_<name>)
  out/census/hooks.txt           the hooked functions, for tools/perf_codegen_post.py --hooked-list

default.xex's Direct3D is [0x82096000, 0x820B4000) (the functions below it neither call the command buffer's space
function nor Direct3D's helpers). A core links only the part of Direct3D it uses, at other addresses: its Direct3D is
the span of its functions whose instructions equal one of default.xex's Direct3D functions with every branch target
ignored. The space function (default.xex sub_820A8FC0, found in each core the same way) is hooked so the census
follows segment switches. Functions that already have a hook (the draw hooks, the D3D GPU wait, the cores' natives)
are left out; the draw hooks call the census themselves.

Census build (PC):
  python tools/d3d_census_build.py
  python tools/perf_codegen_post.py --hooked-list out/census/hooks.txt
  cmake -S app -B out/pc -DFUTARI_CENSUS_DIR=D:/.../out/census ; cmake --build out/pc
  run with futari_diag_d3d_census = true
Back to normal: python tools/perf_codegen_post.py ; cmake -S app -B out/pc -DFUTARI_CENSUS_DIR= ; build.
"""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEN = os.path.join(ROOT, 'app', 'generated')
OUT = os.path.join(ROOT, 'out', 'census')
CORES = ['palm_normal', 'palm_abnormal', 'reco_normal', 'reco_abnormal', 'hirow_normal', 'hirow_abnormal',
         'kiniro_normal', 'kiniro_abnormal']
DEFAULT_RANGE = (0x82096000, 0x820B4000)
DEFAULT_SPACE = 0x820A8FC0
FUNC = re.compile(r'^(?:DEFINE_REX_FUNC|PPC_FUNC_IMPL)\((?:__imp__)?sub_([0-9A-F]{8})\)')
TARGET = re.compile(r'0x[0-9a-f]{8}\b')


def functions(module):
    """{address: tuple(normalized instructions)}"""
    out = {}
    cur = None
    body = []
    for path in sorted(glob.glob(os.path.join(GEN, module, 'futari_recomp.*.cpp'))):
        for line in open(path, encoding='utf-8', errors='replace'):
            m = FUNC.match(line)
            if m:
                if cur is not None:
                    out[cur] = tuple(body)
                cur, body = int(m.group(1), 16), []
                continue
            s = line.strip()
            if cur is not None and s.startswith('// '):
                body.append(TARGET.sub('T', s[3:]))
            elif cur is not None and s == '}' and line.startswith('}'):
                out[cur] = tuple(body)
                cur, body = None, []
    if cur is not None:
        out[cur] = tuple(body)
    return out


def Loose(body):
    """Instructions with every immediate ignored (registers kept)."""
    return tuple(re.sub(r'(?<![rfv\w])-?\d+', 'N', x) for x in body)


def already_hooked():
    """default.xex functions with a hook in the sources, and the core addresses futari_native_core.cpp names."""
    default, core = set(), set()
    for root in (os.path.join(ROOT, 'app', 'src'), os.path.join(ROOT, 'sdk', 'src')):
        for d, _, fs in os.walk(root):
            for f in fs:
                if not f.endswith(('.cpp', '.h', '.c')):
                    continue
                text = open(os.path.join(d, f), encoding='utf-8', errors='ignore').read()
                for m in re.findall(r'REX_HOOK[A-Z_]*\(sub_([0-9A-F]{8})', text):
                    default.add(int(m, 16))
                for m in re.findall(r'FUTARI_HOT_HOOK\(([0-9A-F]{8})', text):
                    default.add(int(m, 16))
                if f == 'futari_native_core.cpp':
                    for m in re.findall(r'(?<![0-9A-Fa-f])(88[0-9A-F]{6})(?![0-9A-Fa-f])', text):
                        core.add(int(m, 16))
    return default, core


def hook(address, space, module_expr, enter, leave, segment):
    name = 'sub_%08X' % address
    lines = ['extern "C" REX_FUNC(__imp__%s);' % name, 'REX_HOOK_RAW(%s) {' % name,
             '  %s(0x%08X, base, %s);' % (enter, address, module_expr)]
    if space:
        lines.append('  %s;' % segment[0])
    lines.append('  __imp__%s(ctx, base);' % name)
    if space:
        lines.append('  %s;' % segment[1])
    lines += ['  %s(base);' % leave, '}']
    return '\n'.join(lines)


def main():
    os.makedirs(OUT, exist_ok=True)
    skip_default, skip_core = already_hooked()
    default = functions('default')
    d3d = {a: body for a, body in default.items() if DEFAULT_RANGE[0] <= a < DEFAULT_RANGE[1]}
    shapes = {}
    for a, body in d3d.items():
        shapes.setdefault(body, []).append(a)
    hooks = []
    text = ['// Generated by tools/d3d_census_build.py: the Direct3D census hooks of default.xex (census builds only).',
            '#include <rex/hook.h>', '#include "%s"' % os.path.join(ROOT, 'app', 'src', 'me',
                                                                    'futari_d3d_census.h').replace('\\', '/'), '']
    n_default = 0
    for a in sorted(d3d):
        if a in skip_default:
            continue
        text.append(hook(a, a == DEFAULT_SPACE, '"default"', 'futari::d3d::CensusEnter', 'futari::d3d::CensusLeave',
                         ('futari::d3d::CensusSegmentBefore(base)', 'futari::d3d::CensusSegmentAfter(base)')))
        hooks.append('sub_%08X default' % a)
        n_default += 1
    open(os.path.join(OUT, 'census_default.cpp'), 'w', encoding='utf-8', newline='\n').write('\n'.join(text) + '\n')

    core_text = ['// Generated by tools/d3d_census_build.py: the Direct3D census hooks of every game core (census '
                 'builds only).', '#include <rex/hook.h>',
                 '#include "%s"' % os.path.join(ROOT, 'app', 'src', 'native', 'futari_native.h').replace('\\', '/'), '']
    summary = []
    space_shape = default[DEFAULT_SPACE]
    for core in CORES:
        funcs = functions(core)
        matched = [a for a, body in funcs.items() if len(body) >= 8 and body in shapes]
        if not matched:
            summary.append('%s: no Direct3D found' % core)
            continue
        lo, hi = min(matched), max(matched)
        span = sorted(a for a in funcs if lo <= a <= hi)
        # The space function reads a global of its module (lis/lwz of an address that differs per module): compared
        # with every immediate ignored.
        space = [a for a, body in funcs.items() if len(body) == len(space_shape) and Loose(body) == Loose(space_shape)]
        core_text.append('#if defined(FUTARI_CORE_%s)' % core)
        n = 0
        for a in span:
            if a in skip_core:
                continue
            core_text.append(hook(a, a in space, '"%s"' % core, 'futari::native::CensusEnter',
                                  'futari::native::CensusLeave',
                                  ('futari::native::CensusSegment(base, 0)', 'futari::native::CensusSegment(base, 1)')))
            hooks.append('sub_%08X %s' % (a, core))
            n += 1
        core_text.append('#endif  // FUTARI_CORE_%s' % core)
        core_text.append('')
        summary.append('%s: Direct3D %08X-%08X, %d functions (%d matching default.xex), %d hooked, space function %s' % (
            core, lo, hi, len(span), len(matched), n, ' '.join('%08X' % a for a in space) or 'NOT FOUND'))
    open(os.path.join(OUT, 'census_core.cpp'), 'w', encoding='utf-8', newline='\n').write('\n'.join(core_text) + '\n')
    open(os.path.join(OUT, 'hooks.txt'), 'w', encoding='utf-8', newline='\n').write('\n'.join(hooks) + '\n')
    print('default: Direct3D %08X-%08X, %d functions, %d hooked (%d already hooked)' % (
        DEFAULT_RANGE[0], DEFAULT_RANGE[1], len(d3d), n_default, len(d3d) - n_default))
    for line in summary:
        print(line)
    print('wrote %s (census_default.cpp, census_core.cpp, hooks.txt: %d hooks)' % (OUT, len(hooks)))


if __name__ == '__main__':
    main()
